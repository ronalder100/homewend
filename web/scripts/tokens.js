// Writes src/lib/tokens.css from tokens.json, the tokens of the design
// system as Claude Design exports them. The design is the source: change it
// there, export again, and this script turns it into CSS custom properties;
// never edit the CSS. Colours have a light and a dark value; type sizes are
// styles; the families are font stacks.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../tokens.json', import.meta.url)));

// The page ships Inter as the variable font, whose family is named so.
const family = (stack) => stack.replace("'Inter'", "'Inter Variable'");

const light = [];
const dark = [];
for (const t of tokens.color.tokens) {
	light.push(`\t--${t.name}: ${t.value.light};`);
	dark.push(`\t--${t.name}: ${t.value.dark};`);
}
for (const [name, stack] of Object.entries(tokens.type.families)) light.push(`\t--font-${name}: ${family(stack)};`);
for (const group of tokens.type.groups) for (const s of group.styles) light.push(`\t--${s.name}: ${s.fontSize};`);

// The system decides unless the person chose: data-theme on <html> wins.
const css = `/* Generated by scripts/tokens.js from tokens.json. Do not edit. */
:root {
\tcolor-scheme: light;
${light.join('\n')}
}
:root[data-theme='dark'] {
\tcolor-scheme: dark;
${dark.join('\n')}
}
@media (prefers-color-scheme: dark) {
\t:root:not([data-theme='light']) {
\t\tcolor-scheme: dark;
${dark.map((l) => '\t' + l).join('\n')}
\t}
}
`;
writeFileSync(new URL('../src/lib/tokens.css', import.meta.url), css);
